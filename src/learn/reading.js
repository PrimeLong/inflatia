// слова цитаты для «найдите в цитате»: каждое слово знает, входит ли оно в искомое место
export function quoteWords(quote, mark = '') {
  const from = mark ? quote.indexOf(mark) : -1;
  const to = from >= 0 ? from + mark.length : -1;
  const out = []; const re = /\S+/g; let m;
  while ((m = re.exec(quote))) out.push({ w: m[0], key: out.length, hit: from >= 0 && m.index >= from && m.index < to });
  return out;
}
